#!/usr/bin/env python3
from __future__ import annotations

KINDS={"key":1,"consumable":2,"weapon":3}
ENEMY_TYPES={"walker":1,"charger":2,"tank":3}

def esc(s):
    return str(s).replace("\\","\\\\").replace('"','\\"')

def generate_rpg(d):
    items=d.get("items",[])
    item_index={x["name"]:i for i,x in enumerate(items)}
    pickups=[]
    for ri,r in enumerate(d.get("rooms",[])):
        for p in r.get("pickups",[]): pickups.append((ri,p))
    dialogs=d.get("dialogues",[])
    choices=[]
    nodes=[]
    dialog_index={x["id"]:i for i,x in enumerate(dialogs)}
    for n in dialogs:
        start=len(choices)
        for c in n.get("choices",[]):
            give=c.get("give_item")
            gi=-1; gq=0
            if give:
                gi=item_index.get(give.get("name",""),-1); gq=int(give.get("qty",1))
            sf=c.get("set_flag")
            sf_name=""; sf_val=0
            if sf:
                sf_name=sf.get("name",""); sf_val=int(sf.get("value",1))
            nxt=dialog_index.get(c.get("next"),-1) if c.get("next") else -1
            choices.append((c.get("text","..."),nxt,sf_name,sf_val,gi,gq))
        nodes.append((n.get("id",""),n.get("text",""),start,len(choices)-start))
    def arr(lines,fallback): return ",\n".join(lines) if lines else fallback
    il=arr([f'    {{ "{esc(x["name"])}", {KINDS[x.get("kind","consumable")]}, {int(x.get("power",0))}, {int(x.get("count",0))}, {int(x.get("count",0))} }}' for x in items],
           '    { "", 0, 0, 0, 0 }')
    pl=arr([f'    {{ {ri}, {int(x["x"])}, {int(x["y"])}, {item_index.get(x["item"],-1)}, {int(x.get("qty",1))}, 0 }}' for ri,x in pickups],
           '    { 0,-1000,-1000,-1,0,1 }')
    nl=arr([f'    {{ "{esc(i)}", "{esc(t)}", {s}, {n} }}' for i,t,s,n in nodes],
           '    { "", "", 0, 0 }')
    cl=arr([f'    {{ "{esc(t)}", {nxt}, "{esc(sf)}", {sv}, {gi}, {gq} }}' for t,nxt,sf,sv,gi,gq in choices],
           '    { "", -1, "", 0, -1, 0 }')
    p=d.get("player",{})
    return f"""/* AUTO-GENERATED by xgm. */
#ifndef GENERATED_RPG_H
#define GENERATED_RPG_H
#define RPG_ITEM_COUNT {len(items)}
#define RPG_PICKUP_COUNT {len(pickups)}
#define DIALOG_NODE_COUNT {len(nodes)}
#define DIALOG_CHOICE_COUNT {len(choices)}
#define PLAYER_MAX_HP {int(p.get("health",5))}
#define PLAYER_BASE_DAMAGE {int(p.get("damage",1))}
static item_t items[{max(1,len(items))}]={{
{il}
}};
static pickup_t pickups[{max(1,len(pickups))}]={{
{pl}
}};
static const dialog_node_t dialog_nodes[{max(1,len(nodes))}]={{
{nl}
}};
static const dialog_choice_t dialog_choices[{max(1,len(choices))}]={{
{cl}
}};
#endif
"""

def enemy_type_id(name):
    return ENEMY_TYPES.get(name,1)
